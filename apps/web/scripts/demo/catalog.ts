export interface DemoVariant {
  size?: string;
  color?: string;
  volume?: string;
  /** سعر الوحدة بعملة المورد */
  cost: number;
  /** الكمية المشتراة (0 = لا يدخل الشحنة: نفد في النظام) */
  qty: number;
}

export interface DemoProduct {
  category: string;
  nameAr: string;
  nameEn: string;
  descAr: string;
  descEn: string;
  supplier: "CN" | "QA";
  shape: Shape;
  /** اللون الرئيسي ولون التفاصيل */
  colors: [string, string];
  variants: DemoVariant[];
  trackExpiry?: boolean;
  /** يبقى بلا سعر معتمد (يظهر في «مراجعة الأسعار» ولا يظهر في المتجر) */
  noPrice?: boolean;
  /** منتج معطّل */
  inactive?: boolean;
}

const v = (cost: number, qty: number, opts: Omit<DemoVariant, "cost" | "qty"> = {}): DemoVariant => ({
  cost,
  qty,
  ...opts,
});

